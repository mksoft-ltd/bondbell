# Create (or reuse) the App Store provisioning profile for this app, install it,
# and write ios/ExportOptions.plist.
#
# WHY THIS EXISTS: `flutter build ipa` exports with *automatic* signing, which
# on this machine dies with "No profiles for 'com.froggyeye.bondbell' were
# found" because no Apple ID is signed into Xcode; and
# `xcodebuild -exportArchive -allowProvisioningUpdates` with the App Store
# Connect key fails with "Cloud signing permission error" — the key's
# App Manager role cannot mint profiles that way. POST /v1/profiles with the
# same key DOES work. (store-publisher memory: ios-ipa-export-needs-manual-profile)
#
#   GEM_HOME=/opt/homebrew/Cellar/fastlane/2.237.0/libexec \
#   GEM_PATH=$GEM_HOME /opt/homebrew/opt/ruby/bin/ruby tools/publish/ios_profile.rb
#
# Idempotent: an existing ACTIVE profile of the right name is reused, not
# duplicated. Profiles are freely regenerable; the certificate is NOT — this
# script never touches certificates beyond reading the existing one.
require_relative "asc"
require "base64"

BUNDLE_ID = "com.froggyeye.bondbell"
PROFILE_NAME = "Bondbell App Store"
REPO = File.expand_path("../..", __dir__)
EXPORT_OPTIONS = "#{REPO}/ios/ExportOptions.plist"
INSTALL_DIR = File.expand_path("~/Library/MobileDevice/Provisioning Profiles")

def h1(t) = puts("\n== #{t} ==")

h1 "bundle id"
code, body = ASC.get("/v1/bundleIds?filter[identifier]=#{BUNDLE_ID}")
ASC.expect!(code, body, 200, context: "looking up bundle id #{BUNDLE_ID}")
bundle = body["data"].first or abort "no bundle id record for #{BUNDLE_ID}"
puts "  #{bundle['id']} #{bundle['attributes']['identifier']}"

h1 "distribution certificate"
code, body = ASC.get("/v1/certificates?filter[certificateType]=DISTRIBUTION&limit=50")
ASC.expect!(code, body, 200, context: "listing certificates")
# Pinned: the 2027 distribution cert whose private key is in the login
# keychain (house-facts §34c). Two identities share the name "Apple
# Distribution: Froggy Eye Ltd", so never pick by name.
CERT_ID = "48CDM5Z29C"
cert = body["data"].find { |c| c["id"] == CERT_ID }
abort "distribution certificate #{CERT_ID} not on the team" unless cert
require "digest"
CERT_SHA1 = Digest::SHA1.hexdigest(Base64.decode64(cert["attributes"]["certificateContent"])).upcase
puts "  sha1=#{CERT_SHA1}"
unless `security find-identity -v -p codesigning`.include?(CERT_SHA1)
  abort "the keychain has no identity for #{CERT_ID} (sha1 #{CERT_SHA1})"
end
puts "  #{cert['id']} #{cert['attributes']['name']} expires=#{cert['attributes']['expirationDate']}"

h1 "profile"
code, body = ASC.get("/v1/profiles?limit=200")
ASC.expect!(code, body, 200, context: "listing profiles")
existing = body["data"].find do |p|
  a = p["attributes"]
  a["name"] == PROFILE_NAME && a["profileType"] == "IOS_APP_STORE" && a["profileState"] == "ACTIVE"
end
if existing
  c2, rel = ASC.get("/v1/profiles/#{existing['id']}/certificates")
  existing = nil unless c2 == 200 && rel["data"].any? { |c| c["id"] == CERT_ID }
end

if existing
  puts "  reusing #{existing['id']} #{existing['attributes']['name']} (ACTIVE)"
  profile = existing
  code, body = ASC.get("/v1/profiles/#{existing['id']}")
  ASC.expect!(code, body, 200, context: "reading profile content")
  profile = body["data"]
else
  puts "  creating #{PROFILE_NAME.inspect}"
  code, body = ASC.post("/v1/profiles", {
    data: {
      type: "profiles",
      attributes: { name: PROFILE_NAME, profileType: "IOS_APP_STORE" },
      relationships: {
        bundleId: { data: { type: "bundleIds", id: bundle["id"] } },
        certificates: { data: [{ type: "certificates", id: cert["id"] }] }
      }
    }
  })
  ASC.expect!(code, body, 201, context: "creating the App Store profile")
  profile = body["data"]
  puts "  created #{profile['id']} state=#{profile['attributes']['profileState']}"
end

h1 "install"
uuid = profile["attributes"]["uuid"]
content = profile["attributes"]["profileContent"] or abort "profile has no content"
Dir.mkdir(INSTALL_DIR) unless Dir.exist?(INSTALL_DIR)
path = File.join(INSTALL_DIR, "#{uuid}.mobileprovision")
File.binwrite(path, Base64.decode64(content))
puts "  #{path} (#{File.size(path)} bytes)"
puts "  uuid=#{uuid} expires=#{profile['attributes']['expirationDate']}"

h1 "ExportOptions.plist"
File.write(EXPORT_OPTIONS, <<~PLIST)
  <?xml version="1.0" encoding="UTF-8"?>
  <!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
  <!-- Generated by tools/publish/ios_profile.rb. Manual signing on purpose:
       cloud signing is refused for this team's App Store Connect API key. -->
  <plist version="1.0">
  <dict>
    <key>method</key>
    <string>app-store-connect</string>
    <key>teamID</key>
    <string>696939LPWV</string>
    <key>signingStyle</key>
    <string>manual</string>
    <key>signingCertificate</key>
    <string>#{CERT_SHA1}</string>
    <key>provisioningProfiles</key>
    <dict>
      <key>#{BUNDLE_ID}</key>
      <string>#{PROFILE_NAME}</string>
    </dict>
    <key>uploadSymbols</key>
    <true/>
    <key>manageAppVersionAndBuildNumber</key>
    <false/>
    <key>destination</key>
    <string>export</string>
  </dict>
  </plist>
PLIST
puts "  wrote #{EXPORT_OPTIONS}"
system("plutil", "-lint", EXPORT_OPTIONS) or abort "ExportOptions.plist is not valid plist"
